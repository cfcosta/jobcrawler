def crawl(ctx):
    page = ctx.fetch(SITE)
    if "jobs.ashbyhq.com/ava-labs" not in page:
        return
    for job in JOBS:
        item = {
            "url": job["url"],
            "title": job["title"],
            "company": COMPANY,
            "location": job["location"],
            "description": job["description"],
            "source": SITE,
        }
        for key in ("department", "employment_type", "workplace_type", "salary", "posted_at", "expires_at", "external_id", "apply_url"):
            value = job.get(key)
            if value:
                item[key] = value
        yield item
