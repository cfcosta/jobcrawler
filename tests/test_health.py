"""Tests for health detection & self-healing regeneration (§4.8).

A site is flagged stale on a *single* zero-items_found run against a baseline
that previously yielded items — never on zero new_items (a healthy low-frequency
feed legitimately adds nothing) — and only after a re-probe that re-parses >= 1
item fails to clear it (one blip is tolerated). A confirmed-stale site is
regenerated by the current generator; exhausting the budget without a
gate-passing crawler is a distinct generation-failed state, not a silent
re-enqueue (which would spin).
"""

from __future__ import annotations

from datetime import datetime, timezone

from bizup_autocrawler.health import (
    HealthState,
    RegenOutcome,
    SelfHealer,
    regeneration_state,
    staleness_candidate,
)
from bizup_autocrawler.state import RunRecord, StateStore

UTC = timezone.utc
T0 = datetime(2026, 1, 1, tzinfo=UTC)


def _run(items: int, new: int = 0) -> RunRecord:
    return RunRecord(
        id=1,
        site="s",
        started=T0,
        finished=T0,
        items_found=items,
        new_items=new,
        errors=0,
        pages_fetched=1,
    )


def test_zero_items_after_baseline_is_a_candidate() -> None:
    assert staleness_candidate([_run(0), _run(8), _run(7)])  # newest-first


def test_zero_items_without_baseline_is_not_a_candidate() -> None:
    assert not staleness_candidate([_run(0), _run(0)])


def test_nonzero_latest_is_not_a_candidate() -> None:
    assert not staleness_candidate([_run(5), _run(8)])


def test_zero_new_items_is_not_staleness() -> None:
    # found items but added nothing new — a healthy low-frequency feed.
    assert not staleness_candidate([_run(8, new=0), _run(8, new=3)])


def test_empty_history_is_not_a_candidate() -> None:
    assert not staleness_candidate([])


def test_regeneration_state_maps_outcome() -> None:
    assert regeneration_state(RegenOutcome.PROMOTED) is HealthState.HEALTHY
    assert regeneration_state(RegenOutcome.STAGED) is HealthState.PENDING_REVIEW
    assert regeneration_state(RegenOutcome.FAILED) is HealthState.GENERATION_FAILED


def _stale_store() -> StateStore:
    store = StateStore(":memory:", clock=lambda: T0)
    baseline = store.start_run("s")
    store.finish_run(baseline, items_found=8, new_items=8, errors=0, pages_fetched=2)
    latest = store.start_run("s")
    store.finish_run(latest, items_found=0, new_items=0, errors=1, pages_fetched=1)
    return store


async def _healer(
    store: StateStore, *, reprobe_items: int, regen_outcome: RegenOutcome
):
    async def reprobe(slug: str) -> int:
        return reprobe_items

    async def regenerate(slug: str) -> RegenOutcome:
        return regen_outcome

    return SelfHealer(store, reprobe=reprobe, regenerate=regenerate)


async def test_healthy_site_is_not_probed_or_regenerated() -> None:
    store = StateStore(":memory:", clock=lambda: T0)
    run_id = store.start_run("s")
    store.finish_run(run_id, items_found=5, new_items=2, errors=0, pages_fetched=1)

    probed = False

    async def reprobe(slug: str) -> int:
        nonlocal probed
        probed = True
        return 0

    async def regenerate(slug: str) -> RegenOutcome:
        raise AssertionError("must not regenerate a healthy site")

    healer = SelfHealer(store, reprobe=reprobe, regenerate=regenerate)
    assert await healer.assess("s") is HealthState.HEALTHY
    assert not probed


async def test_confirmed_failure_invokes_the_capture_hook() -> None:
    # A confirmed real failure (re-probe re-parses nothing) is captured for the §4.11
    # optimizer — the failure signal — before self-healing runs.
    store = _stale_store()
    captured: list[str] = []

    async def reprobe(slug: str) -> int:
        return 0  # re-probe confirms: not a transient outage

    async def regenerate(slug: str) -> RegenOutcome:
        return RegenOutcome.FAILED

    healer = SelfHealer(
        store,
        reprobe=reprobe,
        regenerate=regenerate,
        on_confirmed_failure=captured.append,
    )
    await healer.assess("s")
    assert captured == ["s"]


async def test_a_blip_does_not_invoke_the_capture_hook() -> None:
    # A transient outage (re-probe re-parses items) is NOT a learning signal.
    store = _stale_store()
    captured: list[str] = []

    async def reprobe(slug: str) -> int:
        return 2  # re-parsed → tolerated blip

    async def regenerate(slug: str) -> RegenOutcome:
        raise AssertionError("a blip must not regenerate")

    healer = SelfHealer(
        store,
        reprobe=reprobe,
        regenerate=regenerate,
        on_confirmed_failure=captured.append,
    )
    assert await healer.assess("s") is HealthState.HEALTHY
    assert captured == []


async def test_reprobe_clears_a_blip() -> None:
    healer = await _healer(
        _stale_store(), reprobe_items=3, regen_outcome=RegenOutcome.FAILED
    )
    assert await healer.assess("s") is HealthState.HEALTHY


async def test_confirmed_stale_regenerates_live_and_recovers() -> None:
    # review_gate off (or auto-deliver): the regen goes live → the site is healed.
    healer = await _healer(
        _stale_store(), reprobe_items=0, regen_outcome=RegenOutcome.PROMOTED
    )
    assert await healer.assess("s") is HealthState.HEALTHY


async def test_staged_regen_is_pending_review() -> None:
    # review_gate on (the default, §14.2): a gate-passing crawler is staged for a human
    # to promote, NOT delivered live — the site is awaiting review, not yet healthy.
    store = _stale_store()
    healer = await _healer(store, reprobe_items=0, regen_outcome=RegenOutcome.STAGED)
    assert await healer.assess("s") is HealthState.PENDING_REVIEW
    assert store.get_health("s") == HealthState.PENDING_REVIEW.value


async def test_regeneration_exhaustion_is_generation_failed() -> None:
    healer = await _healer(
        _stale_store(), reprobe_items=0, regen_outcome=RegenOutcome.FAILED
    )
    assert await healer.assess("s") is HealthState.GENERATION_FAILED


# -- persistence & no-spin (§4.8) --------------------------------------------


async def test_assess_persists_the_resulting_state() -> None:
    store = _stale_store()
    healer = await _healer(store, reprobe_items=0, regen_outcome=RegenOutcome.FAILED)
    await healer.assess("s")
    assert store.get_health("s") == HealthState.GENERATION_FAILED.value


async def test_generation_failed_site_is_not_re_regenerated() -> None:
    # The "not silently re-enqueued into the same failing generation" rule: once a
    # stale site has failed generation, a later assessment must surface the failed
    # state without driving the (expensive) generator again — otherwise it spins.
    store = _stale_store()
    regen_calls = 0

    async def reprobe(slug: str) -> int:
        return 0

    async def regenerate(slug: str) -> RegenOutcome:
        nonlocal regen_calls
        regen_calls += 1
        return RegenOutcome.FAILED

    healer = SelfHealer(store, reprobe=reprobe, regenerate=regenerate)
    assert await healer.assess("s") is HealthState.GENERATION_FAILED
    assert await healer.assess("s") is HealthState.GENERATION_FAILED
    assert regen_calls == 1


async def test_recovered_site_clears_generation_failed() -> None:
    # A previously generation-failed site that starts finding items again is healthy
    # (its latest run isn't a staleness candidate); the stuck state must not persist.
    store = _stale_store()
    store.set_health("s", HealthState.GENERATION_FAILED.value)
    recovered = store.start_run("s")
    store.finish_run(recovered, items_found=6, new_items=6, errors=0, pages_fetched=1)

    async def reprobe(slug: str) -> int:
        raise AssertionError("a recovered site must not be re-probed")

    async def regenerate(slug: str) -> RegenOutcome:
        raise AssertionError("a recovered site must not be regenerated")

    healer = SelfHealer(store, reprobe=reprobe, regenerate=regenerate)
    assert await healer.assess("s") is HealthState.HEALTHY
    assert store.get_health("s") == HealthState.HEALTHY.value


async def test_pending_review_site_is_not_re_regenerated() -> None:
    # Same no-spin rule as generation-failed, for the §14.2 staged state: while a
    # regenerated crawler sits awaiting human promotion, a later assessment surfaces
    # PENDING_REVIEW without re-running the (expensive) generator — and without
    # re-staging over the candidate a human is reviewing.
    store = _stale_store()
    regen_calls = 0

    async def reprobe(slug: str) -> int:
        return 0

    async def regenerate(slug: str) -> RegenOutcome:
        nonlocal regen_calls
        regen_calls += 1
        return RegenOutcome.STAGED

    healer = SelfHealer(store, reprobe=reprobe, regenerate=regenerate)
    assert await healer.assess("s") is HealthState.PENDING_REVIEW
    assert await healer.assess("s") is HealthState.PENDING_REVIEW
    assert regen_calls == 1


async def test_promoted_site_clears_pending_review() -> None:
    # Once a human promotes the staged crawler, the live crawler finds items again, so
    # the latest run is no longer a staleness candidate → healthy, clearing the stuck
    # pending-review state (mirrors the generation-failed recovery path).
    store = _stale_store()
    store.set_health("s", HealthState.PENDING_REVIEW.value)
    recovered = store.start_run("s")
    store.finish_run(recovered, items_found=6, new_items=6, errors=0, pages_fetched=1)

    async def reprobe(slug: str) -> int:
        raise AssertionError("a recovered site must not be re-probed")

    async def regenerate(slug: str) -> RegenOutcome:
        raise AssertionError("a recovered site must not be regenerated")

    healer = SelfHealer(store, reprobe=reprobe, regenerate=regenerate)
    assert await healer.assess("s") is HealthState.HEALTHY
    assert store.get_health("s") == HealthState.HEALTHY.value
